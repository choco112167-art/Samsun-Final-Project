# Force-add ignored paths (e.g. data, __pycache__) but NEVER node_modules.
# Usage (repo root):  pwsh ./scripts/git-add-force-no-node_modules.ps1
Set-StrictMode -Version Latest
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)
Set-Location $root

git add -f -- . ":(exclude)node_modules" ":(exclude)frontend/node_modules"
